def test_first_request_auto_provisions_user(client: TestClient, db: Session) -> None:
    """A brand new Supabase user id should get a local profile row on its
    first authenticated request — there's no signup call to this backend,
    Supabase Auth creates the account and this app only sees it later.
    """
    email = random_email()
    user_id = uuid.uuid4()
    token = mint_supabase_token(user_id=user_id, email=email)

    r = client.get(
        f"{settings.API_V1_STR}/users/me",
        headers={"Authorization": f"Bearer {token}"},
    )
    assert r.status_code == 200
    assert r.json()["email"] == email

    db_user = db.get(User, user_id)
    assert db_user
    assert db_user.email == email


